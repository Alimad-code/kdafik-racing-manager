def build_practice_report(
    *,
    profile: TrackProfile,
    wings_setting: int,
    suspension_setting: int,
    gearbox_setting: int,
    driver_id: str,
    stage_id: str,
    segment: PracticeSegment,
) -> PracticeTextReport:
    targets = ideal_setup_targets(profile)
    settings = (wings_setting, suspension_setting, gearbox_setting)
    parameters = ("aerodynamics", "chassis", "transmission")
    labels = ("Аэродинамика", "Шасси", "Трансмиссия")
    stable_key = f"{stage_id}:{driver_id}:{segment.value}"

    assessments: list[tuple[str, SetupDirection, int]] = []
    lines: list[str] = []
    for parameter, label, setting, target in zip(
        parameters,
        labels,
        settings,
        targets,
        strict=True,
    ):
        delta = target - setting
        direction: SetupDirection
        if abs(delta) <= SETUP_WORKING_TOLERANCE:
            direction = "balanced"
        elif delta > 0:
            direction = "increase"
        else:
            direction = "decrease"
        assessments.append((parameter, direction, abs(delta)))
        phrase = _stable_choice(_SETUP_PHRASES[parameter][direction], stable_key, parameter)
        lines.append(f"{label}: {phrase}")

    mismatches = [assessment for assessment in assessments if assessment[1] != "balanced"]
    if not mismatches:
        recommendation = _stable_choice(
            _BALANCED_RECOMMENDATIONS,
            stable_key,
            "balanced-priority",
        )
    else:
        parameter, direction, _ = max(mismatches, key=lambda item: item[2])
        recommendation = _stable_choice(
            _PRIORITY_PHRASES[parameter][direction],
            stable_key,
            f"{parameter}-priority",
        )

    return PracticeTextReport(
        setup_feedback="\n".join(lines),
        engineer_recommendation=recommendation,
    )


def driver_voice(*, pace: int, stability: int) -> DriverVoice:
    if stability >= 84:
        return "analytical"
    if pace >= 83:
        return "assertive"
    if stability <= 75:
        return "emotional"
    return "calm"


