def radio_situation(trigger_type: str, trigger_detail: str | None) -> str:
    if trigger_type == "TECHNICAL_ISSUE":
        return "technical_issue"
    if trigger_type == "INCIDENT":
        detail = (trigger_detail or "").casefold()
        if "блокиров" in detail:
            return "lockup"
        if "лёгк" in detail or "контакт" in detail:
            return "contact"
        if "серьёз" in detail or "авари" in detail:
            return "serious_crash"
    if trigger_type == "RAIN_ON_SLICKS":
        return "rain_on_slicks"
    if trigger_type == "CLIFF_REACHED":
        return "tire_cliff"
    if trigger_type == "TIRE_RULE_WARNING":
        return "tire_rule_warning"
    return "generic"


def build_radio_message(
    *,
    trigger_type: str,
    trigger_detail: str | None,
    driver_id: str,
    pace: int,
    stability: int,
    occurrence_index: int,
) -> str:
    situation = radio_situation(trigger_type, trigger_detail)
    voice = driver_voice(pace=pace, stability=stability)
    phrases = _RADIO_PHRASES[situation][voice]
    start_index = _stable_index(len(phrases), driver_id, situation)
    return phrases[(start_index + occurrence_index) % len(phrases)]


def _stable_choice(values: tuple[str, ...], *parts: str) -> str:
    return values[_stable_index(len(values), *parts)]


def _stable_index(length: int, *parts: str) -> int:
    digest = sha256(":".join(parts).encode("utf-8")).digest()
    return int.from_bytes(digest[:8], "big") % length
