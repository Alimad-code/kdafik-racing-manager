def ideal_setup_targets(profile: TrackProfile) -> tuple[int, int, int]:
    if profile == TrackProfile.SPEED:
        return 20, 70, 80
    if profile == TrackProfile.TECHNICAL:
        return 80, 30, 20
    return 50, 50, 50


